# 7. RESEND OTP SERIALIZER
#    POST /auth/resend-otp/
# ─────────────────────────────────────────────────────────────────────────────

class ResendOTPSerializer(serializers.Serializer):
    """
    Validates resend eligibility.
    Checks resend_count and resend_blocked_until before allowing.
    """

    phone = serializers.CharField(max_length=20, required=True, help_text='Phone number the OTP was originally sent to.')
    purpose = serializers.ChoiceField(
        choices=PhoneVerification.Purpose.choices, required=True,
        help_text='Purpose of the OTP: signup, login, password_reset, or phone_change.'
    )

    def validate_phone(self, value: str) -> str:
        return validate_phone_format(value)

    def validate(self, attrs: dict) -> dict:
        phone = attrs.get('phone')
        purpose = attrs.get('purpose')

        qs = (
            PhoneVerification.objects
            .used()
            .for_phone(phone)
            .by_purpose(purpose)
        )

        # PHONE_CHANGE and PASSWORD_RESET both have a real user by this point —
        # scope to them so resend can't be triggered against someone else's row.
        if purpose == PhoneVerification.Purpose.PHONE_CHANGE:
            request = self.context.get('request')
            if not request or not request.user.is_authenticated:
                raise serializers.ValidationError({'phone': 'Authentication required.'})
            qs = qs.filter(user=request.user)
        elif purpose == PhoneVerification.Purpose.PASSWORD_RESET:
            user = User.objects.by_phone(phone).first()
            if user:
                qs = qs.filter(user=user)

        verification = qs.order_by('-created_at', '-id').first()

        if not verification:
            raise serializers.ValidationError({
                'phone': 'Phone Number Expired. Please start over.'
            })

        if verification.is_resend_locked():
            remaining = verification.resend_blocked_until - timezone.now()
            total_seconds = int(remaining.total_seconds())

            if total_seconds <= 60:
                message = f"Try again after {total_seconds} seconds."

            elif total_seconds < 3600:
                minutes = total_seconds // 60
                message = f"Try again after {minutes} minute(s)."

            else:
                hours = total_seconds // 3600
                minutes = (total_seconds % 3600) // 60

                if minutes:
                    message = f"Try again after {hours} hour(s) and {minutes} minute(s)."
                else:
                    message = f"Try again after {hours} hour(s)."


            raise serializers.ValidationError({
                'phone': f'Too many OTP requests. {message}'
            })

        attrs['_verification'] = verification
        return attrs


