# 1. SIGNUP SERIALIZER
#    POST /auth/signup/
# ─────────────────────────────────────────────────────────────────────────────

class SignupSerializer(serializers.Serializer):
    """
    Validates registration input.
    User creation is deferred until OTP is verified in SignupVerifyOTPSerializer.
    NOTE: uniqueness is re-checked in the service at creation time — two people
    starting signup with the same phone close together can both pass this
    check, so the final guard has to live inside the atomic transaction.
    """

    first_name = serializers.CharField(max_length=50, required=True, help_text='User first name. Letters only.')
    last_name = serializers.CharField(max_length=50, required=True, help_text='User last name. Letters only.')
    phone = serializers.CharField(max_length=20, required=True, help_text='International format. Example: +251912345678')
    email = serializers.EmailField(max_length=150, required=False, allow_blank=True)
    password = serializers.CharField(
        max_length=128, required=True, write_only=True,
        style={'input_type': 'password'}, help_text='Must meet strength requirements.'
    )
    confirm_password = serializers.CharField(
        max_length=128, required=True, write_only=True,
        style={'input_type': 'password'}, help_text='Must match password exactly.'
    )
    role = serializers.ChoiceField(choices=[UserRole.OWNER, UserRole.PLAYER])

    def validate_first_name(self, value: str) -> str:
        value = value.strip()
        if not value.replace(' ', '').isalpha():
            raise serializers.ValidationError('First name must contain letters only.')
        return value.capitalize()

    def validate_last_name(self, value: str) -> str:
        value = value.strip()
        if not value.replace(' ', '').isalpha():
            raise serializers.ValidationError('Last name must contain letters only.')
        return value.capitalize()

    def validate_phone(self, value: str) -> str:
        value = validate_phone_format(value)
        if User.objects.filter(phone=value, deleted_at__isnull=True).exists():
            raise serializers.ValidationError('An account with this phone number already exists.')
        return value

    def validate_password(self, value: str) -> str:
        return validate_password_strength(value)

    def validate(self, attrs: dict) -> dict:
        if attrs['password'] != attrs['confirm_password']:
            raise serializers.ValidationError({'confirm_password': 'Passwords do not match.'})
        return attrs


