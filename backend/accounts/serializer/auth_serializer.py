# 5. FORGOT PASSWORD VERIFY OTP SERIALIZER
#    POST /auth/forgot-password/verify/
#
#    FIX: now scoped by user too. PASSWORD_RESET always has a real User by
#    this point (unlike SIGNUP), so we look the user up by phone and filter
#    the verification query by that user — preventing any edge case where a
#    stale/duplicate row for the same phone number gets matched instead.
# ─────────────────────────────────────────────────────────────────────────────

class ForgotPasswordVerifyOTPSerializer(serializers.Serializer):
    """
    Verifies OTP for the password reset flow.
    On success the service issues a short-lived reset_token.
    """

    phone = serializers.CharField(max_length=20, required=True, help_text='Same phone number used in ForgotPasswordSerializer.')
    otp_code = serializers.CharField(
        max_length=5, min_length=5, required=True, write_only=True, help_text='5-digit OTP sent to phone.'
    )

    def validate_phone(self, value: str) -> str:
        return validate_phone_format(value)

    def validate_otp_code(self, value: str) -> str:
        if not value.isdigit():
            raise serializers.ValidationError('OTP must contain digits only.')
        return value

    def validate(self, attrs: dict) -> dict:
        phone = attrs.get('phone')
        otp_code = attrs.get('otp_code')

        user = User.objects.by_phone(phone).first()
        if not user:
            # Keep the same generic error as an unmatched OTP — don't leak
            # whether the phone number exists on this endpoint either.
            raise serializers.ValidationError({
                'otp_code': 'OTP expired. Please request a new one.'
            })

        verification = (
            PhoneVerification.objects
            .valid()
            .for_phone(phone)
            .by_purpose(PhoneVerification.Purpose.PASSWORD_RESET)
            .filter(user=user)
            .order_by('-created_at', '-id')
            .first()
        )

        if not verification:
            raise serializers.ValidationError({
                'otp_code': 'OTP expired. Please request a new one.'
            })

        if verification.is_locked():
            time = format_lockout_duration(verification.attempts_locked_until)
            raise serializers.ValidationError({
                'otp_code': f'Too many incorrect attempts. Try again in {time}.'
            })
        
      

        if not verification.check_otp(otp_code):
            verification.increment_attempts()
            verification.refresh_from_db()
            remaining = PhoneVerification.MAX_ATTEMPTS - verification.attempts
            raise serializers.ValidationError({
                'otp_code': f'Incorrect OTP.'
            })

        attrs['_verification'] = verification
        attrs['_user'] = user
        return attrs


