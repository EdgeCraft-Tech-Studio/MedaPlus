# 2. SIGNUP VERIFY OTP SERIALIZER
#    POST /auth/signup/verify/
#
#    NOTE: no user FK filter here by design — at signup time no User row
#    exists yet, so PhoneVerification.user is null for SIGNUP purpose.
# ─────────────────────────────────────────────────────────────────────────────



class SignupVerifyOTPSerializer(DeviceInfoMixin, serializers.Serializer):
    """
    Verifies OTP for the signup flow.
    Attaches the PhoneVerification row as validated_data['_verification'].
    """

    phone = serializers.CharField(max_length=20, required=True, help_text='Same phone number used in SignupSerializer.')
    otp_code = serializers.CharField(
        max_length=5, min_length=5, required=True, write_only=True, help_text='5-digit OTP sent to phone.'
    )

    def validate_phone(self, value: str) -> str:
        return validate_phone_format(value)

    def validate_otp_code(self, value: str) -> str:
        if not value.isdigit():
            raise serializers.ValidationError('OTP must contain digits only.')
        return value

    def validate(self, attrs: dict) -> dict:
        phone = attrs.get('phone')
        otp_code = attrs.get('otp_code')

        verification = (
            PhoneVerification.objects
            .valid()
            .for_phone(phone)
            .by_purpose(PhoneVerification.Purpose.SIGNUP)
            .order_by('-created_at', '-id')
            .first()
        )

        if not verification:
            raise serializers.ValidationError({
                'otp_code': 'OTP expired. Please request a new one.'
            })

        if verification.is_locked():
            time = format_lockout_duration(verification.attempts_locked_until)
            raise serializers.ValidationError({
                'otp_code': f'Too many incorrect attempts. Try again in {time}.'
            })

       

        if not verification.check_otp(otp_code):
            verification.increment_attempts()
            verification.refresh_from_db()
            remaining = PhoneVerification.MAX_ATTEMPTS - verification.attempts
            raise serializers.ValidationError({
                'otp_code': f'Incorrect OTP.'
            })

        attrs['_verification'] = verification
        return attrs


