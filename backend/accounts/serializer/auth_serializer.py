# 8. TOKEN REFRESH SERIALIZER
#    POST /auth/token/refresh/
# ─────────────────────────────────────────────────────────────────────────────

class TokenRefreshSerializer(serializers.Serializer):
    """
    Validates refresh_token format before passing to the service.
    Service handles hash lookup and session rotation.
    """

    refresh_token = serializers.CharField(required=True, write_only=True, help_text='Refresh token issued at login. Valid for 30 days.')

    def validate_refresh_token(self, value):
        value = value.strip()
        if not value:
            raise serializers.ValidationError("Refresh token cannot be empty")
        return value

    def validate(self, attrs):
        token = attrs["refresh_token"]
        hashed = hashlib.sha256(token.encode()).hexdigest()

        session = (
            UserSession.objects
            .select_related("user")
            .filter(refresh_token_hash=hashed, is_revoked=False)
            .first()
        )

        if not session:
            raise serializers.ValidationError({"refresh_token": "Invalid or expired refresh token"})

        if not session.is_refresh_valid:
            raise serializers.ValidationError({"refresh_token": "Session expired or revoked"})

        attrs["_session"] = session
        return attrs


