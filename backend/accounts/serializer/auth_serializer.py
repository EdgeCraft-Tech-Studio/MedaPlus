# 3. LOGIN SERIALIZER
#    POST /auth/login/
# ─────────────────────────────────────────────────────────────────────────────

class LoginSerializer(DeviceInfoMixin, serializers.Serializer):
    """
    Validates credentials and account state.
    Session creation is handled by auth_service.create_session() after validation.
    """

    phone = serializers.CharField(max_length=20, required=True, help_text='Registered phone number in international format.')
    password = serializers.CharField(required=True, write_only=True, style={'input_type': 'password'}, help_text='Account password.')

    def validate_phone(self, value: str) -> str:
        return validate_phone_format(value)

    def validate(self, attrs: dict) -> dict:
        phone = attrs.get('phone')
        password = attrs.get('password')

        user = User.objects.by_phone(phone).first()

        if not user:
            raise serializers.ValidationError({
                'detail': 'Invalid phone number or password.'
            })

        if user.is_deleted:
            raise serializers.ValidationError({
                'detail': 'Invalid phone number or password.'
            })
            

        if not user.active:
            raise serializers.ValidationError({
                'detail': 'Invalid phone number or password.'
            })
            

        if user.is_blocked:
            remaining_minutes = max(
                1,
                int((user.blocked_until - timezone.now()).total_seconds() / 60)
            )
            user.reset_failed_attempts()

            raise serializers.ValidationError({
                'phone': f'Too many failed attempts. Try again after {remaining_minutes} minutes.'
            })  

        if not user.check_password(password):
            user.increment_failed_attempts() 
            remaining = max(0, 5 - user.failed_attempts)
            if remaining == 0:
                raise serializers.ValidationError({
                    'password': f'Too many failed attempts please try again later after {remaining}.'
                })
            raise serializers.ValidationError({'Invalid Crediential': f'Invalid phone number or password'})

        attrs['_user'] = user
        return attrs


