# 10. REQUEST PHONE CHANGE SERIALIZER
#     POST /accounts/me/phone/request/
# ─────────────────────────────────────────────────────────────────────────────

class RequestPhoneChangeSerializer(serializers.Serializer):
    """
    Validates new phone before OTP is sent to it.
    """

    password = serializers.CharField(write_only=True)
    new_phone = serializers.CharField(max_length=20, required=True, help_text='New phone number in international format.')

    def validate_password(self, value: str) -> str:
        user = self.context['request'].user
        if not user.check_password(value):
            raise serializers.ValidationError('Invalid phone number or password')
        return value

    def validate_new_phone(self, value: str) -> str:
        value = validate_phone_format(value)

        if User.objects.filter(phone=value, deleted_at__isnull=True).exists():
            raise serializers.ValidationError('This phone number is already registered to another account.')

        current_user = self.context['request'].user
        if value == current_user.phone:
            raise serializers.ValidationError('New phone number must be different from your current phone number.')

        return value


